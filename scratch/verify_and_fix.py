def replace_block(lines, start_sub, end_sub, replacement_lines, start_from=0, search_backwards=False):
    start_idx = -1
    for idx in range(start_from, len(lines)):
        if start_sub in lines[idx]:
            start_idx = idx
            break
    if start_idx == -1:
        print(f"Warning: could not find start: '{start_sub}'")
        return -1
    
    end_idx = -1
    if search_backwards:
        for idx in range(len(lines) - 1, start_idx - 1, -1):
            if end_sub in lines[idx]:
                end_idx = idx + 1
                break
    else:
        for idx in range(start_idx, len(lines)):
            if end_sub in lines[idx]:
                end_idx = idx + 1
                break
    if end_idx == -1:
        print(f"Warning: could not find end: '{end_sub}'")
        return -1
    
    lines[start_idx:end_idx] = replacement_lines
    return start_idx + len(replacement_lines)

