def verify_and_save(src_path, dest_path, clean_func):
    content = clean_func()
    try:
        compile(content, dest_path, 'exec')
        print(f"Success compiling {dest_path}!")
        open(dest_path, 'w', encoding='utf-8').write(content)
        return True
    except SyntaxError as e:
        open(dest_path, 'w', encoding='utf-8').write(content)
        err_text = str(e.text).encode('utf-8', errors='replace').decode('utf-8') if e.text else "None"
        print(f"SyntaxError in {dest_path} at line {e.lineno}: {err_text}")
        lines = content.splitlines()
        start = max(0, e.lineno - 5)
        end = min(len(lines), e.lineno + 5)
        for idx in range(start, end):
            line_str = lines[idx].encode('utf-8', errors='replace').decode('utf-8')
            print(f"{idx+1}: {line_str}")
        return False

